#!/usr/bin/env python3
"""Copy Resources/pricing.json into PricingData.swift, so loading prices never needs a resource bundle.

The JSON file stays the single source: the prototype reads it, and a test fails until this script
has been run after an edit.

    python3 -I scripts/embed-pricing.py
"""
import os

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
SOURCE = os.path.join(ROOT, "Sources", "RunningOutCore", "Resources", "pricing.json")
TARGET = os.path.join(ROOT, "Sources", "RunningOutCore", "PricingData.swift")

with open(SOURCE, encoding="utf-8") as fh:
    text = fh.read()
if not text.endswith("\n") or '"""#' in text or "\\#" in text:
    raise SystemExit("pricing.json must end with a newline and must not contain raw-string delimiters")

body = "\n".join(("        " + line) if line else "" for line in text[:-1].split("\n"))
with open(TARGET, "w", encoding="utf-8") as fh:
    fh.write(
        "// Generated by scripts/embed-pricing.py from Resources/pricing.json. Do not edit by hand.\n"
        "\n"
        "extension PriceTable {\n"
        "    /// A verbatim copy of `Resources/pricing.json`; a test keeps the two equal.\n"
        '    static let embeddedJSON = #"""\n'
        f"{body}\n"
        '        """#\n'
        "}\n"
    )
print(f"wrote {os.path.relpath(TARGET, ROOT)}")
